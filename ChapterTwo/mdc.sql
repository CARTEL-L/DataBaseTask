-- NUMBER EIGHT H-- 
SELECT MAX(TOTALAMOUNT) AS MAXIMUM_AMOUNT,
MIN(TOTALAMOUNT) AS MINIMUM_AMOUNT
FROM INVOICE;

-- NUMBER NINE I-- 
SELECT AVG(TOTALAMOUNT) AS AVERAGE_TOTALAMOUNT
FROM INVOICE;

-- NUMBER TEN J-- 
SELECT COUNT(FIRSTNAME) AS NUMBER_OF_CUSTOMERS
FROM CUSTOMER;

-- NUMBER ELEVEN K-- 
