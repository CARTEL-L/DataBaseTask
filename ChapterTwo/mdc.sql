FROM CUSTOMER
group by LASTNAME, FIRSTNAME;

-- NUMBER TWELVE L-- 
SELECT LASTNAME, FIRSTNAME, COUNT(*) AS MATCHINGNAMES
FROM CUSTOMER
GROUP BY LASTNAME, FIRSTNAME;

